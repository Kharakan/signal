// Package preserve provides pure string-building primitives for annotating
// deleted and edited messages instead of redacting / overwriting them in
// Matrix. It has no dependencies on bridgev2, signalmeow or cgo so it can be
// unit-tested in isolation and shared between connector and msgconv.
package preserve

import (
	"fmt"
	"html"
	"strings"
	"time"
)

// Templates bundles the configurable strings for annotating deleted or edited
// messages. All templates are plain text; HTML escaping is applied when
// rendering the formatted body so user-supplied templates cannot inject markup.
type Templates struct {
	Redacted        string // placeholder: {timestamp}
	Edited          string // placeholder: {timestamp}
	EditedMulti     string // placeholders: {timestamp}, {count}
	OriginalLabel   string // shown above the strikethrough'd original
	VersionLabel    string // placeholder: {n} — shown per history entry
	TimestampFormat string // Go time.Format layout
	MaxEditHistory  int    // 0 = show only direct predecessor strikethrough'd
}

// Fragment carries paired plain and HTML representations of the same logical
// content. Consumers assign Body to event.MessageEventContent.Body and
// FormattedBody to .FormattedBody (with Format = event.FormatHTML).
type Fragment struct {
	Body          string
	FormattedBody string
}

// WrapStrikethrough produces a strikethrough'd version of the given content.
// Plain text uses ~~markdown-style~~ tildes (Element renders this; other
// clients show literal tildes — acceptable fallback). HTML uses <del>.
//
// If formattedIn is empty, it is generated by HTML-escaping bodyIn so the
// returned FormattedBody is never empty.
//
// Plain text is wrapped per-line — multi-line ~~...~~ does not render as
// strikethrough in Element.
func WrapStrikethrough(bodyIn, formattedIn string) Fragment {
	if formattedIn == "" {
		formattedIn = html.EscapeString(bodyIn)
	}
	lines := strings.Split(bodyIn, "\n")
	for i, line := range lines {
		if line != "" {
			lines[i] = "~~" + line + "~~"
		}
	}
	return Fragment{
		Body:          strings.Join(lines, "\n"),
		FormattedBody: "<del>" + formattedIn + "</del>",
	}
}

// RenderTimestamp formats t with the configured layout. Returns "" if layout
// is empty so callers can defer error handling to config validation.
func RenderTimestamp(t time.Time, layout string) string {
	if layout == "" {
		return ""
	}
	return t.Format(layout)
}

// BuildRedactionMarker renders the marker line shown when a sender has deleted
// a message for everyone. The template's {timestamp} placeholder is substituted
// with the formatted timestamp.
func BuildRedactionMarker(tpl Templates, t time.Time) Fragment {
	text := strings.ReplaceAll(tpl.Redacted, "{timestamp}", RenderTimestamp(t, tpl.TimestampFormat))
	return Fragment{
		Body:          text,
		FormattedBody: html.EscapeString(text),
	}
}

// BuildEditMarker renders the marker line shown when a sender has edited a
// message. For count > 1 the multi-edit template is used; otherwise the
// single-edit template. Templates may reference {timestamp} and {count}.
func BuildEditMarker(tpl Templates, t time.Time, count int) Fragment {
	ts := RenderTimestamp(t, tpl.TimestampFormat)
	var text string
	if count > 1 {
		text = strings.ReplaceAll(tpl.EditedMulti, "{timestamp}", ts)
		text = strings.ReplaceAll(text, "{count}", fmt.Sprintf("%d", count))
	} else {
		text = strings.ReplaceAll(tpl.Edited, "{timestamp}", ts)
	}
	return Fragment{
		Body:          text,
		FormattedBody: html.EscapeString(text),
	}
}

// BuildVersionLabel renders the per-version prefix shown in edit history,
// e.g. "v2:". {n} is substituted with the version number.
func BuildVersionLabel(tpl Templates, n int) string {
	return strings.ReplaceAll(tpl.VersionLabel, "{n}", fmt.Sprintf("%d", n))
}

// AppendBlock glues an additional block below the receiver, separated by a
// blank line in plain text and a single <br> in HTML. Used to attach marker
// lines and version-history blocks to the current message content.
func (a Fragment) AppendBlock(block Fragment) Fragment {
	var b, fb strings.Builder
	if a.Body != "" {
		b.WriteString(a.Body)
		b.WriteString("\n")
	}
	b.WriteString(block.Body)

	if a.FormattedBody != "" {
		fb.WriteString(a.FormattedBody)
		fb.WriteString("<br>")
	}
	fb.WriteString(block.FormattedBody)

	return Fragment{Body: b.String(), FormattedBody: fb.String()}
}
